"""Thirty prompts for each of the nine identities in the face-erasure set.

Three rules, and every prompt obeys all three.

The face is visible. Identity is what is being erased, so a shot from behind or
from across a square measures nothing, and ArcFace needs a face to embed.

No scene is reused, within a person or between people. Identical scenes across
identities push the model toward one averaged face and blur exactly the signal
we are after; the assertion at the bottom refuses duplicates.

Context never names the person. "The President addressing Congress" renders
Obama however well the face was erased, because identity leaks through the
role. Every prompt is the name plus a scene that would suit anyone, which is
the only way the metric measures erasure rather than censorship of context.

DEMOGRAPHIC holds the target of the `demo` mapping. The wording follows the
coarse apparent-appearance categories used in face fairness benchmarks. It
describes how a face reads on screen, not what anyone is. The reason to carry
this much is that a poorer target lets the model fill the gap from its own
prior, which is not demographically neutral: mapping every erased identity onto
"a person" quietly turns them all into the same default face.
"""

